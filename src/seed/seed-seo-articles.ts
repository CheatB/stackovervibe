async function seed() {
  console.log("━━━ SEED: SEO-статьи ━━━\n");

  const payload = await getPayload({ config });

  /* Найти или создать admin-пользователя */
  const { docs: admins } = await payload.find({
    collection: "users",
    where: { role: { equals: "admin" } },
    limit: 1,
  });

  if (admins.length === 0) {
    console.log("❌ Нет admin-пользователя для авторства!");
    process.exit(1);
  }

  const adminId = admins[0].id;
  const статьи = [статья1, статья2, статья3, статья4, статья5];

  /* Кэш тегов по slug */
  const кэшТегов: Record<string, number> = {};
  const { docs: всеТеги } = await payload.find({
    collection: "tags",
    limit: 100,
  });
  for (const тег of всеТеги) {
    кэшТегов[тег.slug] = тег.id;
  }

  for (const статья of статьи) {
    /* Проверить дубликат */
    const { docs: существующие } = await payload.find({
      collection: "posts",
      where: { slug: { equals: статья.slug } },
      limit: 1,
    });

    if (существующие.length > 0) {
      const тегиIds = (статья.теги || [])
        .map((slug: string) => кэшТегов[slug])
        .filter(Boolean);
      await payload.update({
        collection: "posts",
        id: существующие[0].id,
        data: {
          title: статья.title,
          content: статья.content as any,
          tags: тегиIds,
          seoTitle: статья.seoTitle,
          seoDescription: статья.seoDescription,
        },
      });
      console.log(`  [UPD] ${статья.slug} — обновлён`);
      continue;
    }

    /* Разрешить теги */
    const тегиIds = (статья.теги || [])
      .map((slug: string) => кэшТегов[slug])
      .filter(Boolean);

    await payload.create({
      collection: "posts",
      data: {
        title: статья.title,
        slug: статья.slug,
        content: статья.content as any,
        author: adminId,
        tags: тегиIds,
        status: "published",
        publishedAt: new Date().toISOString(),
        seoTitle: статья.seoTitle,
        seoDescription: статья.seoDescription,
      },
    });

    console.log(`  [OK] ${статья.slug} — создан и опубликован`);
  }

  console.log("\n━━━ ГОТОВО ━━━");
  process.exit(0);
}

