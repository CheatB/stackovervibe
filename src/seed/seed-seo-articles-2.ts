/* ===== Хелперы Lexical ===== */
function p(text: string) {
  return {
    type: "paragraph",
    version: 1,
    children: [
      {
        type: "text",
        text,
        version: 1,
        format: 0,
        mode: "normal",
        detail: 0,
        style: "",
      },
    ],
    direction: "ltr" as const,
    format: "" as const,
    indent: 0,
    textFormat: 0,
    textStyle: "",
  };
}

function h2(text: string) {
  return {
    type: "heading",
    tag: "h2",
    version: 1,
    children: [
      {
        type: "text",
        text,
        version: 1,
        format: 0,
        mode: "normal",
        detail: 0,
        style: "",
      },
    ],
    direction: "ltr" as const,
    format: "" as const,
    indent: 0,
  };
}

function h3(text: string) {
  return {
    type: "heading",
    tag: "h3",
    version: 1,
    children: [
      {
        type: "text",
        text,
        version: 1,
        format: 0,
        mode: "normal",
        detail: 0,
        style: "",
      },
    ],
    direction: "ltr" as const,
    format: "" as const,
    indent: 0,
  };
}

function lexical(children: any[]) {
  return {
    root: {
      type: "root",
      children,
      direction: "ltr",
      format: "",
      indent: 0,
      version: 1,
    },
  };
}

